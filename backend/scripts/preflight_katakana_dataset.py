"""Read-only provenance and completeness preflight for an externally installed Katakana dataset."""
import csv
import hashlib
import json
import sys
from collections import defaultdict
from pathlib import Path

import cv2

BACKEND_DIR = Path(__file__).resolve().parents[1]
DATA_DIR = BACKEND_DIR / "data" / "katakana_dataset"
MANIFEST_PATH = DATA_DIR / "dataset_manifest.json"
ANNOTATIONS_PATH = DATA_DIR / "annotations.csv"
CLASSES = tuple("アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヲン")
MIN_SAMPLES_PER_CLASS = 200
MIN_WRITERS_PER_CLASS = 50
REQUIRED_CITATION = "Electrotechnical Laboratory, Japanese Technical Committee for Optical Character Recognition, ETL Character Database, 1973-1984."


def stop(message):
    print("NOT READY:", message)
    return 2


def main():
    if not MANIFEST_PATH.is_file() or not ANNOTATIONS_PATH.is_file():
        return stop(f"Install the AIST ETL6 data locally and provide {MANIFEST_PATH.name} plus {ANNOTATIONS_PATH.name}. No dataset is present or generated by this tool.")

    try:
        manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return stop(f"Cannot read dataset manifest: {exc}")

    required = {
        "script_code": "ja-katakana",
        "dataset_name": "ETL6",
        "source_url": "https://etlcdb.db.aist.go.jp/the-etl-character-database/",
        "license_name": "AIST ETL Character Database Terms of Use",
        "terms_of_use_accepted": True,
        "citation": REQUIRED_CITATION,
    }
    for key, expected in required.items():
        if manifest.get(key) != expected:
            return stop(f"Manifest field {key!r} must be {expected!r}.")
    if not str(manifest.get("terms_accepted_date", "")).strip():
        return stop("Record the date when you personally accepted AIST's Terms of Use.")
    archive_hash = str(manifest.get("source_archive_sha256", "")).lower()
    if len(archive_hash) != 64 or any(c not in "0123456789abcdef" for c in archive_hash):
        return stop("source_archive_sha256 must contain the SHA-256 of the original ETL6 archive.")

    root = DATA_DIR.resolve()
    rows = []
    seen_names = set()
    seen_hashes = {}
    by_class = defaultdict(list)
    try:
        with ANNOTATIONS_PATH.open("r", encoding="utf-8-sig", newline="") as handle:
            reader = csv.DictReader(handle)
            expected_headers = {"filename", "character", "writer_id"}
            if not reader.fieldnames or not expected_headers.issubset(set(reader.fieldnames)):
                return stop("annotations.csv must have filename, character, and writer_id columns.")
            for line, row in enumerate(reader, start=2):
                name = (row.get("filename") or "").strip()
                char = (row.get("character") or "").strip()
                writer = (row.get("writer_id") or "").strip()
                if not name or not writer or char not in CLASSES:
                    return stop(f"Invalid filename/character/writer_id at annotations.csv line {line}.")
                image_path = (DATA_DIR / name).resolve()
                try:
                    image_path.relative_to(root)
                except ValueError:
                    return stop(f"Image path escapes the dataset directory at line {line}.")
                if image_path in seen_names:
                    return stop(f"Image path is listed more than once: {name}")
                seen_names.add(image_path)
                if image_path.suffix.lower() not in {".png", ".jpg", ".jpeg", ".bmp", ".tif", ".tiff"} or not image_path.is_file():
                    return stop(f"Missing or unsupported image file at line {line}: {name}")
                image = cv2.imread(str(image_path), cv2.IMREAD_GRAYSCALE)
                if image is None or image.size == 0:
                    return stop(f"Unreadable image at line {line}: {name}")
                digest = hashlib.sha256(image_path.read_bytes()).hexdigest()
                if digest in seen_hashes:
                    return stop(f"Exact duplicate images found: {seen_hashes[digest]} and {name}")
                seen_hashes[digest] = name
                item = {"filename": name, "writer_id": writer}
                by_class[char].append(item)
                rows.append(item)
    except OSError as exc:
        return stop(f"Could not read annotation or image files: {exc}")

    missing = [char for char in CLASSES if not by_class[char]]
    if missing:
        return stop("Missing Katakana classes: " + " ".join(missing))
    low_samples = {char: len(by_class[char]) for char in CLASSES if len(by_class[char]) < MIN_SAMPLES_PER_CLASS}
    if low_samples:
        return stop(f"At least {MIN_SAMPLES_PER_CLASS} samples per class are required; low counts: {low_samples}")
    low_writers = {char: len({item["writer_id"] for item in by_class[char]}) for char in CLASSES if len({item["writer_id"] for item in by_class[char]}) < MIN_WRITERS_PER_CLASS}
    if low_writers:
        return stop(f"At least {MIN_WRITERS_PER_CLASS} distinct writers per class are required; low counts: {low_writers}")

    print("READY FOR WRITER-DISJOINT TRAINING (this tool did not train or write anything)")
    print(f"Dataset: AIST ETL6 · {len(CLASSES)} Katakana classes · {len(rows)} readable images")
    print(f"Writers across classes: {len({item['writer_id'] for item in rows})}")
    print(f"Source archive SHA-256: {archive_hash}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
